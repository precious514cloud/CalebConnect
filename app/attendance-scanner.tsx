import AsyncStorage from '@react-native-async-storage/async-storage';
import { CameraView, useCameraPermissions } from 'expo-camera';
import { router } from 'expo-router';
import { useEffect, useRef, useState } from 'react';
import {
  ActivityIndicator,
  Alert,
  Pressable,
  SafeAreaView,
  StyleSheet,
  Text,
  View,
} from 'react-native';

import { supabase } from '../lib/supabase';

const PROFILE_KEY = '@calebconnect_student_profile';

type StudentProfile = {
  id?: string;
  fullName: string;
  matricNumber: string;
  programme: string;
  level: string;
};

type ScannedSession = {
  lecturerId: string;
  sessionId: string;
  courseCode: string;
  courseTitle: string;
  topic: string;
  date: string;
  startTime: string;
  duration: string;
  venue: string;
  level: string;
  rotationNumber: number;
  rotationSeconds: number;
  issuedAt: number;
  expiresAt: number;
  rawPayload: string;
};

type SupabaseProfile = {
  id: string;
  full_name: string;
  student_id: string | null;
  department: string | null;
  level: string | null;
};

type AttendanceSessionRow = {
  id: string;
  lecturer_id: string;
  course_id: string;
  session_code: string;
  topic: string | null;
  class_date: string;
  start_time: string | null;
  duration: number;
  venue: string | null;
  status: string;
  level: string | null;
};

export default function AttendanceScannerScreen() {
  const [permission, requestPermission] = useCameraPermissions();
  const [scanned, setScanned] = useState(false);
  const [saving, setSaving] = useState(false);
  const [loadingProfile, setLoadingProfile] = useState(true);
  const [session, setSession] = useState<ScannedSession | null>(null);
  const [studentProfile, setStudentProfile] =
    useState<StudentProfile | null>(null);
  const [errorMessage, setErrorMessage] = useState<string | null>(null);

  // Remember the last rejected QR so the camera does not repeatedly
  // process the same expired screenshot after the student taps Scan Again.
  const lastRejectedQrRef = useRef<string | null>(null);

  useEffect(() => {
    loadStudentProfile();
  }, []);

  const loadStudentProfile = async () => {
    try {
      setLoadingProfile(true);

      const savedProfile = await AsyncStorage.getItem(PROFILE_KEY);

      if (!savedProfile) {
        Alert.alert(
          'Student Profile Required',
          'Please complete your student profile before scanning attendance.',
          [
            {
              text: 'Set Up Profile',
              onPress: () => router.replace('/student-setup'),
            },
          ]
        );
        return;
      }

      const profile: StudentProfile = JSON.parse(savedProfile);

      if (!profile.fullName || !profile.matricNumber) {
        Alert.alert(
          'Incomplete Student Profile',
          'Your student profile is missing required information. Please complete your profile again.',
          [
            {
              text: 'Set Up Profile',
              onPress: () => router.replace('/student-setup'),
            },
          ]
        );
        return;
      }

      setStudentProfile(profile);
    } catch (error) {
      console.error('Load student profile error:', error);

      Alert.alert(
        'Profile Error',
        'Unable to load your student profile.'
      );
    } finally {
      setLoadingProfile(false);
    }
  };

  /*
   * QR EXPIRY VALIDATION
   *
   * The lecturer's QR contains:
   * rotationNumber, rotationSeconds, issuedAt and expiresAt.
   *
   * A QR is rejected once its expiry timestamp has passed.
   */

  const isQrStillValid = (qrSession: ScannedSession): boolean => {
    const now = Date.now();

    return (
      Number.isFinite(qrSession.issuedAt) &&
      Number.isFinite(qrSession.expiresAt) &&
      Number.isFinite(qrSession.rotationNumber) &&
      Number.isFinite(qrSession.rotationSeconds) &&
      qrSession.issuedAt > 0 &&
      qrSession.expiresAt > qrSession.issuedAt &&
      qrSession.rotationNumber >= 1 &&
      qrSession.rotationSeconds >= 1 &&
      qrSession.expiresAt - qrSession.issuedAt <=
        qrSession.rotationSeconds * 1000 + 1000 &&
      now >= qrSession.issuedAt - 30000 &&
      now < qrSession.expiresAt
    );
  };

  /*
   * Show expiry inside the scanner screen instead of using a native
   * Alert popup. Remember the rejected payload so it cannot repeatedly
   * trigger the expiry message while it remains in camera view.
   */

  const showExpiredQr = (
    rawPayload: string,
    message: string
  ) => {
    lastRejectedQrRef.current = rawPayload;
    setSession(null);
    setErrorMessage(message);
    setScanned(true);
  };

  /*
   * QR FORMAT GENERATED BY THE LECTURER'S QR SCREEN:
   *
   * 0  CALEB_ATTENDANCE
   * 1  lecturerId
   * 2  sessionId
   * 3  courseCode
   * 4  courseTitle
   * 5  topic
   * 6  date
   * 7  startTime
   * 8  duration
   * 9  venue
   * 10 level
   * 11 rotationNumber
   * 12 rotationSeconds
   * 13 issuedAt
   * 14 expiresAt
   */

  const handleBarcodeScanned = ({ data }: { data: string }) => {
    if (scanned || saving) {
      return;
    }

    // Ignore the exact QR payload that was already rejected.
    // A newly rotated QR has a different payload and can be scanned.
    if (lastRejectedQrRef.current === data) {
      return;
    }

    if (lastRejectedQrRef.current !== null) {
      lastRejectedQrRef.current = null;
    }

    setScanned(true);
    setErrorMessage(null);

    if (!data.startsWith('CALEB_ATTENDANCE|')) {
      Alert.alert(
        'Invalid QR Code',
        'This QR code is not a CalebConnect attendance code.',
        [{ text: 'Try Again', onPress: scanAgain }]
      );
      return;
    }

    const parts = data.split('|');

    if (parts.length !== 15) {
      Alert.alert(
        'Invalid Attendance Code',
        'This QR code has an invalid format. Please scan the current QR code displayed by your lecturer.',
        [{ text: 'Try Again', onPress: scanAgain }]
      );
      return;
    }

    const scannedSession: ScannedSession = {
      lecturerId: parts[1]?.trim() || '',
      sessionId: parts[2]?.trim() || '',
      courseCode: parts[3]?.trim() || '',
      courseTitle: parts[4]?.trim() || '',
      topic: parts[5]?.trim() || '',
      date: parts[6]?.trim() || '',
      startTime: parts[7]?.trim() || '',
      duration: parts[8]?.trim() || '',
      venue: parts[9]?.trim() || '',
      level: parts[10]?.trim() || '',
      rotationNumber: Number(parts[11]),
      rotationSeconds: Number(parts[12]),
      issuedAt: Number(parts[13]),
      expiresAt: Number(parts[14]),
      rawPayload: data,
    };

    if (
      !scannedSession.lecturerId ||
      !scannedSession.sessionId ||
      !scannedSession.courseCode
    ) {
      Alert.alert(
        'Invalid Attendance Code',
        'The QR code is missing required attendance information.',
        [{ text: 'Try Again', onPress: scanAgain }]
      );
      return;
    }

    // Reject expired QR immediately, without repeatedly opening Alerts.
    if (!isQrStillValid(scannedSession)) {
      showExpiredQr(
        data,
        'This QR code has expired or is no longer valid. Ask your lecturer to display the current QR code, then scan it.'
      );
      return;
    }

    setSession(scannedSession);
  };

  /*
   * FIND THE STUDENT'S SUPABASE PROFILE
   */

  const findStudentProfile = async (): Promise<SupabaseProfile | null> => {
    if (!studentProfile) {
      return null;
    }

    const { data, error } = await supabase
      .from('profiles')
      .select('id, full_name, student_id, department, level')
      .eq('student_id', studentProfile.matricNumber)
      .maybeSingle();

    if (error) {
      console.error('Find student profile error:', error);
      throw error;
    }

    if (data) {
      return data as SupabaseProfile;
    }

    const { data: authData, error: authError } =
      await supabase.auth.getUser();

    if (authError) {
      console.log('Auth user lookup:', authError.message);
    }

    const authUser = authData?.user;

    if (authUser?.id) {
      const {
        data: authProfile,
        error: authProfileError,
      } = await supabase
        .from('profiles')
        .select('id, full_name, student_id, department, level')
        .eq('id', authUser.id)
        .maybeSingle();

      if (authProfileError) {
        console.error(
          'Find profile by auth user error:',
          authProfileError
        );
      }

      if (authProfile) {
        return authProfile as SupabaseProfile;
      }
    }

    return null;
  };

  /*
   * VERIFY THAT THE ATTENDANCE SESSION EXISTS
   */

  const verifyAttendanceSession =
    async (): Promise<AttendanceSessionRow | null> => {
      if (!session) {
        return null;
      }

      const { data, error } = await supabase
        .from('attendance_sessions')
        .select(`
          id,
          lecturer_id,
          course_id,
          session_code,
          topic,
          class_date,
          start_time,
          duration,
          venue,
          status,
          level
        `)
        .eq('id', session.sessionId)
        .eq('lecturer_id', session.lecturerId)
        .maybeSingle();

      if (error) {
        console.error(
          'Verify attendance session error:',
          error
        );
        throw error;
      }

      return data as AttendanceSessionRow | null;
    };

  /*
   * MARK ATTENDANCE
   */

  const markAttendance = async () => {
    if (saving) {
      return;
    }

    if (!studentProfile) {
      Alert.alert(
        'Profile Required',
        'Your student profile could not be found.'
      );
      return;
    }

    if (!session) {
      Alert.alert(
        'No Session',
        'No attendance session was detected.'
      );
      return;
    }

    // First expiry check: before database operations.
    if (!isQrStillValid(session)) {
      showExpiredQr(
        session.rawPayload,
        'This QR code expired before you confirmed attendance. Ask your lecturer to display the current QR code, then scan it.'
      );
      return;
    }

    try {
      setSaving(true);

      const profile = await findStudentProfile();

      if (!profile) {
        Alert.alert(
          'Student Not Found',
          `We could not find a CalebConnect profile for matric number ${studentProfile.matricNumber}.\n\nPlease make sure your student profile has been registered in CalebConnect.`
        );
        return;
      }

      const attendanceSession = await verifyAttendanceSession();

      if (!attendanceSession) {
        Alert.alert(
          'Session Not Found',
          'This attendance session could not be found in CalebConnect.',
          [{ text: 'Scan Again', onPress: scanAgain }]
        );
        return;
      }

      const sessionStatus = String(
        attendanceSession.status || ''
      ).toLowerCase();

      if (sessionStatus !== 'active') {
        Alert.alert(
          'Attendance Closed',
          'This attendance session is no longer active. You cannot mark attendance for this session.',
          [{ text: 'OK', onPress: () => router.back() }]
        );
        return;
      }

      if (attendanceSession.id !== session.sessionId) {
        Alert.alert(
          'Invalid Session',
          'The attendance session information does not match the QR code.',
          [{ text: 'Scan Again', onPress: scanAgain }]
        );
        return;
      }

      if (attendanceSession.lecturer_id !== session.lecturerId) {
        Alert.alert(
          'Invalid Lecturer',
          'This QR code does not match the attendance session.',
          [{ text: 'Scan Again', onPress: scanAgain }]
        );
        return;
      }

      // Second expiry check: immediately before inserting.
      if (!isQrStillValid(session)) {
        showExpiredQr(
          session.rawPayload,
          'The QR code expired before attendance could be saved. Ask your lecturer to display the current QR code, then scan it.'
        );
        return;
      }

      const now = new Date();

      const {
        data: insertedRecord,
        error: attendanceError,
      } = await supabase
        .from('attendance_records')
        .insert({
          session_id: session.sessionId,
          student_id: profile.id,
          status: 'Present',
          scanned_at: now.toISOString(),
        })
        .select(`
          id,
          session_id,
          student_id,
          status,
          scanned_at,
          created_at
        `)
        .single();

      if (attendanceError) {
        console.error(
          'Supabase attendance insert error:',
          attendanceError
        );

        if (attendanceError.code === '23505') {
          Alert.alert(
            'Already Recorded',
            'Your attendance for this class has already been recorded.',
            [{ text: 'Done', onPress: () => router.back() }]
          );
          return;
        }

        if (attendanceError.code === '23503') {
          Alert.alert(
            'Attendance Could Not Be Recorded',
            'The student or attendance session could not be matched with the CalebConnect database.'
          );
          return;
        }

        if (
          attendanceError.code === '42501' ||
          attendanceError.message?.toLowerCase().includes('row-level security') ||
          attendanceError.message?.toLowerCase().includes('permission')
        ) {
          Alert.alert(
            'Permission Error',
            'Supabase Row Level Security prevented the attendance record from being saved.'
          );
          return;
        }

        Alert.alert(
          'Unable to Record Attendance',
          attendanceError.message ||
            'Something went wrong while saving your attendance.'
        );
        return;
      }

      if (!insertedRecord) {
        Alert.alert(
          'Attendance Error',
          'No attendance record was returned by Supabase.'
        );
        return;
      }

      Alert.alert(
        'Attendance Recorded',
        `Your attendance for ${session.courseCode} has been recorded successfully.`,
        [{ text: 'Done', onPress: () => router.back() }]
      );
    } catch (error: any) {
      console.error('Save attendance error:', error);

      Alert.alert(
        'Unable to Record Attendance',
        error?.message ||
          'Something went wrong while saving your attendance. Please try again.'
      );
    } finally {
      setSaving(false);
    }
  };

  /*
   * RESET THE SCANNER
   *
   * Do not clear lastRejectedQrRef here. Keeping it allows the scanner
   * to ignore the same expired QR still visible in front of the camera.
   * A newly rotated QR has a different payload and will be processed.
   */

  const scanAgain = () => {
    if (saving) {
      return;
    }

    setScanned(false);
    setSession(null);
    setErrorMessage(null);
  };

  /*
   * LOADING PROFILE
   */

  if (loadingProfile) {
    return (
      <SafeAreaView style={styles.loadingContainer}>
        <ActivityIndicator size="large" color="#4F46E5" />
        <Text style={styles.loadingText}>
          Loading student profile...
        </Text>
      </SafeAreaView>
    );
  }

  /*
   * CAMERA PERMISSION CHECK
   */

  if (!permission) {
    return (
      <SafeAreaView style={styles.loadingContainer}>
        <Text style={styles.loadingText}>
          Checking camera permission...
        </Text>
      </SafeAreaView>
    );
  }

  if (!permission.granted) {
    return (
      <SafeAreaView style={styles.permissionContainer}>
        <View style={styles.permissionCard}>
          <Text style={styles.permissionIcon}>📷</Text>

          <Text style={styles.permissionTitle}>
            Camera Permission Required
          </Text>

          <Text style={styles.permissionText}>
            CalebConnect needs access to your camera to scan
            attendance QR codes.
          </Text>

          <Pressable
            style={styles.permissionButton}
            onPress={requestPermission}
          >
            <Text style={styles.permissionButtonText}>
              Allow Camera Access
            </Text>
          </Pressable>

          <Pressable
            style={styles.cancelButton}
            onPress={() => router.back()}
          >
            <Text style={styles.cancelButtonText}>
              Go Back
            </Text>
          </Pressable>
        </View>
      </SafeAreaView>
    );
  }

  /*
   * MAIN SCREEN
   */

  return (
    <SafeAreaView style={styles.container}>
      <View style={styles.cameraContainer}>
        <CameraView
          style={styles.camera}
          facing="back"
          barcodeScannerSettings={{
            barcodeTypes: ['qr'],
          }}
          onBarcodeScanned={
            scanned ? undefined : handleBarcodeScanned
          }
        />

        <View style={styles.header}>
          <Pressable
            style={styles.backButton}
            onPress={() => router.back()}
          >
            <Text style={styles.backButtonText}>‹</Text>
          </Pressable>

          <Text style={styles.headerTitle}>
            Scan Attendance
          </Text>

          <View style={styles.headerSpacer} />
        </View>

        {!scanned && (
          <View style={styles.scannerOverlay}>
            <View style={styles.scannerFrame}>
              <View style={styles.cornerTopLeft} />
              <View style={styles.cornerTopRight} />
              <View style={styles.cornerBottomLeft} />
              <View style={styles.cornerBottomRight} />
            </View>

            <Text style={styles.instructionTitle}>
              Scan Attendance QR Code
            </Text>

            <Text style={styles.instructionText}>
              Position the current QR code inside the box
            </Text>
          </View>
        )}

        {scanned && session ? (
          <View style={styles.resultPanel}>
            <View style={styles.successIcon}>
              <Text style={styles.successIconText}>✓</Text>
            </View>

            <Text style={styles.resultTitle}>
              Attendance QR Detected
            </Text>

            <Text style={styles.resultCode}>
              {session.courseCode}
            </Text>

            <Text style={styles.resultName}>
              {session.courseTitle}
            </Text>

            {session.topic ? (
              <Text style={styles.resultTopic}>
                {session.topic}
              </Text>
            ) : null}

            <View style={styles.lecturerPreview}>
              <Text style={styles.lecturerPreviewLabel}>
                LECTURER ID
              </Text>

              <Text style={styles.lecturerPreviewId}>
                {session.lecturerId}
              </Text>
            </View>

            <View style={styles.studentPreview}>
              <Text style={styles.studentPreviewLabel}>
                ATTENDING AS
              </Text>

              <Text style={styles.studentPreviewName}>
                {studentProfile?.fullName}
              </Text>

              <Text style={styles.studentPreviewDetails}>
                {studentProfile?.matricNumber}
              </Text>

              <Text style={styles.studentPreviewDetails}>
                {studentProfile?.programme} • {studentProfile?.level}
              </Text>
            </View>

            <View style={styles.qrStatus}>
              <Text style={styles.qrStatusText}>
                QR VERSION {session.rotationNumber}
              </Text>
              <Text style={styles.qrStatusText}>
                Expires at{' '}
                {new Date(session.expiresAt).toLocaleTimeString()}
              </Text>
            </View>

            <Text style={styles.resultMessage}>
              Confirm that this is the course you are attending.
              The QR code must still be valid when you mark attendance.
            </Text>

            <Pressable
              style={[
                styles.markButton,
                saving && styles.disabledButton,
              ]}
              onPress={markAttendance}
              disabled={saving}
            >
              {saving ? (
                <View style={styles.savingContent}>
                  <ActivityIndicator color="#FFFFFF" size="small" />
                  <Text style={styles.markButtonText}>
                    Recording...
                  </Text>
                </View>
              ) : (
                <Text style={styles.markButtonText}>
                  ✓ Mark Attendance
                </Text>
              )}
            </Pressable>

            <Pressable
              style={styles.scanAgainButton}
              onPress={scanAgain}
              disabled={saving}
            >
              <Text style={styles.scanAgainText}>
                Scan Another QR
              </Text>
            </Pressable>
          </View>
        ) : scanned ? (
          <View style={styles.invalidPanel}>
            <View style={styles.errorIcon}>
              <Text style={styles.errorIconText}>!</Text>
            </View>

            <Text style={styles.invalidTitle}>
              {errorMessage
                ? 'QR Code Expired'
                : 'QR Code Not Accepted'}
            </Text>

            <Text style={styles.invalidText}>
              {errorMessage ||
                'The QR code is invalid or no longer current. Scan the latest QR code displayed by your lecturer.'}
            </Text>

            <Pressable
              style={styles.scanAgainButton}
              onPress={scanAgain}
            >
              <Text style={styles.scanAgainText}>
                Scan Current QR
              </Text>
            </Pressable>
          </View>
        ) : (
          <View style={styles.bottomPanel}>
            <Text style={styles.bottomIcon}>📱</Text>

            <Text style={styles.bottomTitle}>
              Attendance Scanner
            </Text>

            <Text style={styles.bottomText}>
              Scan the current QR code provided by your lecturer
              or course representative to record your attendance.
            </Text>
          </View>
        )}
      </View>
    </SafeAreaView>
  );
}

